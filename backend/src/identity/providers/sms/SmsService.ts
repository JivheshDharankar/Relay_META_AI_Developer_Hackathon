import { SmsDispatchResult, SmsProvider, VerificationCheckResult } from './types';
import { TwilioSmsProvider } from './TwilioSmsProvider';
import { TwilioVerifyProvider } from './TwilioVerifyProvider';
import { MockSmsProvider } from './MockSmsProvider';
import { env } from '../../../config/env';

export class SmsService {
  private twilioProvider: TwilioSmsProvider;
  private twilioVerifyProvider: TwilioVerifyProvider;
  private mockProvider: MockSmsProvider;
  private providerOverride?: 'twilio' | 'mock';

  constructor(
    twilio?: TwilioSmsProvider,
    mock?: MockSmsProvider,
    verify?: TwilioVerifyProvider
  ) {
    this.twilioProvider = twilio ?? new TwilioSmsProvider();
    this.mockProvider = mock ?? new MockSmsProvider();
    this.twilioVerifyProvider = verify ?? new TwilioVerifyProvider();
  }

  public setProviderOverride(override?: 'twilio' | 'mock'): void {
    this.providerOverride = override;
  }

  public get isTwilioSelected(): boolean {
    if (this.providerOverride) {
      return this.providerOverride === 'twilio';
    }
    const setting = process.env.SMS_PROVIDER || env?.SMS_PROVIDER;
    return setting === 'twilio';
  }

  public get activeProvider(): SmsProvider {
    if (this.isTwilioSelected) {
      return this.twilioProvider;
    }
    return this.mockProvider;
  }

  public get verifyProvider(): TwilioVerifyProvider {
    return this.twilioVerifyProvider;
  }

  public get isLive(): boolean {
    return this.isTwilioSelected && this.twilioVerifyProvider.isConfigured;
  }

  /**
   * Dispatches an OTP verification code via SMS.
   * If Twilio is selected: uses Twilio Verify SMS (code generated by Twilio).
   * If mock is selected: uses MockSmsProvider.
   * Invariant: Never logs raw OTP codes in server console or audit logs.
   */
  public async sendOtp(phone: string, otpCode?: string): Promise<SmsDispatchResult> {
    if (this.isTwilioSelected) {
      // STRICT REQUIREMENT: Fail closed if Twilio is selected but configuration is missing/invalid.
      // Never silently fall back to mock.
      const configCheck = this.twilioVerifyProvider.validateConfig();
      if (!configCheck.valid) {
        return {
          success: false,
          messageId: '',
          providerName: 'twilio-verify',
          errorCode: 'TWILIO_UNCONFIGURED',
          errorMessage: configCheck.error || 'Twilio Verify is selected (SMS_PROVIDER=twilio) but configuration is incomplete or invalid.',
        };
      }
      return this.twilioVerifyProvider.sendVerification(phone);
    }

    const code = otpCode || '123456';
    const body = `Your Relay verification code is: ${code}. Valid for 5 minutes. Do not share this code.`;
    return this.mockProvider.sendSms(phone, body);
  }

  /**
   * Checks an OTP code for a destination phone.
   */
  public async checkVerification(phone: string, code: string): Promise<VerificationCheckResult> {
    if (this.isTwilioSelected) {
      return this.twilioVerifyProvider.checkVerification(phone, code);
    }
    // Mock provider verification fallback (only when mock is explicitly active)
    return {
      success: true,
      status: 'approved',
      providerName: 'mock',
    };
  }

  public getMockProvider(): MockSmsProvider {
    return this.mockProvider;
  }

  public getTwilioProvider(): TwilioSmsProvider {
    return this.twilioProvider;
  }

  public getVerifyProvider(): TwilioVerifyProvider {
    return this.twilioVerifyProvider;
  }
}

export const smsService = new SmsService();
