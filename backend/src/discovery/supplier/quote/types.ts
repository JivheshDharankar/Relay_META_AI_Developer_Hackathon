import { RFQ } from '../rfq/types';

/**
 * Transport channels through which a supplier can transmit their response.
 */
export type SupplierResponseChannel =
  | 'email'
  | 'portal'
  | 'api'
  | 'webhook'
  | 'manual';

/**
 * Ingestion lifecycle status of a raw supplier response.
 */
export type SupplierResponseStatus =
  | 'RECEIVED'
  | 'PROCESSING'
  | 'NORMALIZED'
  | 'REJECTED'
  | 'FAILED';

/**
 * Raw line item as reported by the supplier in their response.
 */
export interface SupplierResponseLineItem {
  /**
   * Reference to the requested product ID (if recognized).
   */
  productId?: string;

  /**
   * How the product identity was established: deterministic catalog match
   * or validated open-world (Meta-understood) identity. Absent for legacy
   * lines that predate identity tracking.
   */
  identitySource?: 'catalog' | 'open-world';

  /**
   * Product description or catalog name as offered by the supplier.
   */
  productName: string;

  /**
   * Quantity the supplier is capable of delivering.
   */
  quotedQuantity: number;

  /**
   * Unit of measurement quoted by the supplier.
   */
  unit: string;

  /**
   * Unit price quoted by the supplier (exclusive of taxes/delivery unless stated).
   */
  unitPrice: number;

  /**
   * Whether the supplier confirmed active warehouse stock for this item.
   */
  inStock?: boolean;

  /**
   * Optional notes on packaging or SKU specifications.
   */
  notes?: string;

  /**
   * Price discovery provenance & live web search evidence
   */
  pricingUnit?: string;
  merchant?: string;
  sourceUrl?: string;
  provenanceStatus?: string;
  packageSizeNote?: string;
}

/**
 * Normalized representation of an ingested raw supplier response.
 * Precedes deterministic financial calculation and quote normalization.
 */
export interface SupplierResponse {
  /**
   * Unique response identifier.
   */
  id: string;

  /**
   * Originating RFQ identifier.
   */
  rfqId: string;

  /**
   * Supplier candidate ID.
   */
  candidateId: string;

  /**
   * Supplier business name.
   */
  supplierName: string;

  /**
   * Ingestion channel.
   */
  channel: SupplierResponseChannel;

  /**
   * Unique message / tracking ID from the transport provider (e.g. email Message-ID, webhook event ID).
   */
  providerMessageId?: string;

  /**
   * External reference or quote number generated by the supplier's ERP/billing system.
   */
  supplierReference?: string;

  /**
   * Quoted line items.
   */
  lineItems: SupplierResponseLineItem[];

  /**
   * Delivery fee quoted by the supplier (if any).
   */
  deliveryFee?: number;

  /**
   * Tax / GST amount quoted by the supplier (if specified).
   */
  tax?: number;

  /**
   * Other miscellaneous charges (handling, packaging, platform fee).
   */
  otherCharges?: number;

  /**
   * Total price as explicitly calculated or stated by the supplier.
   */
  supplierProvidedTotal?: number;

  /**
   * Quoted delivery turnaround in hours from order confirmation.
   */
  deliveryEtaHours?: number;

  /**
   * Explicit delivery date/time committed by the supplier.
   */
  confirmedDeliveryEta?: Date;

  /**
   * True when commercial values were generated by Relay's deterministic
   * simulation for evaluation (no live supplier participated). Absent/false
   * means the response arrived through a real supplier channel.
   */
  isSimulated?: boolean;

  /**
   * Deadline until which the quote terms remain legally binding.
   */
  validUntil?: Date;

  /**
   * Ingestion lifecycle status.
   */
  status: SupplierResponseStatus;

  /**
   * Idempotency key for deduplication.
   */
  idempotencyKey: string;

  /**
   * UTC timestamp when Relay received the supplier's response.
   */
  receivedAt: Date;

  /**
   * Normalized quote ID (populated once successfully converted).
   */
  quoteId?: string;

  /**
   * Failure details if response rejected.
   */
  failureReason?: string;

  /**
   * Reference to the originating RFQ entity.
   */
  rfq: RFQ;
}

/**
 * Deterministic status of a normalized quote.
 */
export type QuoteStatus =
  | 'RECEIVED'
  | 'VALIDATING'
  | 'VALID'
  | 'PARTIAL'
  | 'INVALID'
  | 'EXPIRED'
  | 'SUPERSEDED';

/**
 * Standard machine-readable validation reason codes for quote evaluation.
 */
export type QuoteValidationReasonCode =
  | 'QUOTE_VALID'
  | 'PARTIAL_QUANTITY_OFFERED'
  | 'INVALID_QUANTITY'
  | 'INVALID_UNIT'
  | 'INVALID_UNIT_PRICE'
  | 'QUOTE_TOTAL_MISMATCH'
  | 'DELIVERY_DEADLINE_EXCEEDED'
  | 'DELIVERY_TIME_UNKNOWN'
  | 'QUOTE_EXPIRED'
  | 'RFQ_NOT_FOUND'
  | 'SUPPLIER_MISMATCH'
  | 'RFQ_INACTIVE'
  | 'DUPLICATE_RESPONSE';

/**
 * Normalized line item with Decimal financial precision and fulfillment tracking.
 */
export interface QuoteLineItem {
  productId?: string;
  identitySource?: 'catalog' | 'open-world';
  productName: string;
  requestedQuantity: number;
  quotedQuantity: number;
  isPartial: boolean;
  unit: string;
  unitPrice: number;
  lineSubtotal: number;
  notes?: string;
  pricingUnit?: string;
  merchant?: string;
  sourceUrl?: string;
  provenanceStatus?: string;
  packageSizeNote?: string;
}

/**
 * First-class, normalized, mathematically verified supplier quote.
 * Serves as the immutable financial source of truth for AI negotiation and winner selection.
 */
export interface Quote {
  id: string;
  rfqId: string;
  candidateId: string;
  supplierName: string;
  responseId: string;
  channel: SupplierResponseChannel;
  currency: string;

  lineItems: QuoteLineItem[];

  /**
   * Sum of all line item subtotals (quotedQuantity × unitPrice).
   */
  subtotal: number;

  /**
   * Delivery / logistics charge.
   */
  deliveryFee: number;

  /**
   * Applicable tax / GST.
   */
  tax: number;

  /**
   * Other verified charges (handling, packaging, etc.).
   */
  otherCharges: number;

  /**
   * Deterministically calculated grand total (subtotal + deliveryFee + tax + otherCharges).
   * NEVER blindly trusts supplier-provided total.
   */
  total: number;

  /**
   * Supplier-stated total (recorded for discrepancy audits).
   */
  supplierProvidedTotal?: number;

  /**
   * True when the source response was generated by Relay's deterministic
   * simulation for evaluation (no live supplier participated).
   */
  isSimulated?: boolean;

  /**
   * True if supplier's stated total differs from the calculated total.
   */
  hasTotalMismatch: boolean;

  /**
   * Numeric difference if total mismatch exists (supplierProvidedTotal - total).
   */
  totalMismatchDifference?: number;

  /**
   * Confirmed delivery turnaround in hours (if stated).
   */
  deliveryEtaHours?: number;

  /**
   * Confirmed delivery ETA deadline.
   */
  confirmedDeliveryEta?: Date;

  /**
   * Delivery commitment classification.
   */
  deliveryCommitment: 'CONFIRMED' | 'UNKNOWN' | 'EXCEEDED';

  /**
   * Quote validity expiration timestamp.
   */
  validUntil: Date;

  /**
   * Deterministic qualification status.
   */
  status: QuoteStatus;

  /**
   * Auditable reason codes explaining the status.
   */
  reasons: QuoteValidationReasonCode[];

  /**
   * Sub-list of hard failure reason codes.
   */
  rejectionReasons: QuoteValidationReasonCode[];

  /**
   * Idempotency key for deduplication.
   */
  idempotencyKey: string;

  /**
   * Timestamps.
   */
  receivedAt: Date;
  normalizedAt: Date;
  updatedAt: Date;

  /**
   * Composed reference to the original raw response.
   */
  response: SupplierResponse;
}

/**
 * Result returned upon quote normalization.
 */
export interface NormalizedQuoteResult {
  quote: Quote;
  isDuplicate?: boolean;
}

